// Keep the calendar's Vue bridge on the published kit's actual styles and tokens.
import { readFileSync, writeFileSync, mkdirSync, cpSync } from 'node:fs';
import { bakeNSlice, rect } from 'lino-ui/nslice';
const source = new URL('../node_modules/lino-ui/', import.meta.url);
const projectTokens = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const {cutIcon, iconsModule, ROW} = await import(new URL('src/ds/icon-bake.js', source));
const icons = {};
for (const name of ['calendar','clock','lock']) {
  let svg = readFileSync(new URL(`../public/assets/calendar/card-icon-${name}.svg`, import.meta.url), 'utf8');
  // The package parser reads path attributes, not inherited <g fill>. Ink sizing
  // deliberately ignores the source frame/translation, just like kit icons.
  if (name !== 'lock') svg = svg.replace('<path ', '<path fill="#000000" ');
  icons[`calendar-${name}`] = cutIcon(svg, {textures:[ROW],amount:18/27.5,grain:18/27.5});
}
writeFileSync(new URL('../src/lib/lino-calendar-icons.js', import.meta.url), iconsModule(icons, {
  name:'CALENDAR_ICONS', register:'lino-ui/icon', header:'// Generated by scripts/generate-lino-kit.mjs using lino-ui icon-bake.\n',
}));
const tokens = readFileSync(new URL('src/ds/tokens.css', source), 'utf8');
const start = tokens.indexOf(':root {');
const base = tokens.slice(start + ':root {'.length, tokens.indexOf('\n}', start));
const fonts = tokens.slice(0, start).replaceAll("url('/fonts/", "url('/assets/lino/fonts/");
const css = readFileSync(new URL('src/lib/lino.css', source), 'utf8');
const buttons = css.slice(0, css.indexOf('/* ---------- toolbar'));
const tags = css.slice(css.indexOf('/* ---------- tag:'), css.indexOf('/* ---------- picture:'));
const controls = css.slice(css.indexOf('/* ---------- toggle group:'),css.indexOf('/* ---------- button group:'))
  + css.slice(css.indexOf('/* ---------- input and its label:'),css.indexOf('/* ---------- swatch:'))
  + css.slice(css.indexOf('/* ---------- menus'),css.indexOf('/* ---------- keys'));
writeFileSync(new URL('../src/styles/lino-kit.css', import.meta.url),
  `/* Generated from lino-ui 0.2.0 by scripts/generate-lino-kit.mjs. */\n${fonts}\n.user-calendar--lino {${base}\n}\n@scope (.user-calendar--lino) {\n${buttons}\n${tags}\n${controls}\n}\n`);
mkdirSync(new URL('../public/assets/lino/', import.meta.url), { recursive: true });
cpSync(new URL('fonts/', source), new URL('../public/assets/lino/fonts/', import.meta.url), {recursive:true});
const surfaces = {};
for (const kind of ['plate', 'tag', 'day']) for (let seed = 0; seed < 3; seed++) {
  const border = kind === 'tag' ? 2.75 : 2;
  surfaces[kind + seed] = bakeNSlice({
    cols: [16, {repeat:24}, 16], rows: [16, {repeat:24}, 16],
    texture: {...(kind === 'day' ? projectTokens.interfaceLibrary.dayFrameTexture : {size:24,radius:1.5,octaves:2}),seed:5 + seed}, bleed:4,res:4,
    layers:[{d:rect(0,0,56,56)},{d:rect(border,border,56-border*2,56-border*2)}],
  });
}
writeFileSync(new URL('../src/lib/lino-surfaces-baked.json', import.meta.url), JSON.stringify(surfaces));
console.log('Generated scoped lino kit styles, fonts and nine reusable surface cuts.');
